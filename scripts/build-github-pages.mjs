// Builds the static twin of the demo: the imported database, the pictures and
// the vanilla front end in scripts/pages/, with no server and no API.
//
//   node scripts/build-github-pages.mjs

import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { basename, join, resolve } from 'node:path';

const source = resolve('scripts/pages');
const output = resolve('gh-pages-dist');
const database = JSON.parse(
  await readFile(resolve('data/content-db.json'), 'utf8'),
);
// Ship the optimised derivatives, not the multi-megabyte originals.
const manifest = JSON.parse(
  await readFile(resolve('data/media-manifest.json'), 'utf8'),
).files;
const normalized = (value) =>
  String(value)
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .toLocaleLowerCase('en')
    .trim();
const safeHint = (variant) => {
  const hint = variant.hint?.trim() ?? '';
  const leaksAnswer = variant.answers.some((answer) => {
    const clean = normalized(answer);
    return clean.length > 1 && normalized(hint).includes(clean);
  });
  return leaksAnswer ? '' : hint;
};

// The local static preview may still have an asset open while rebuilding.
await rm(output, {
  recursive: true,
  force: true,
  maxRetries: 5,
  retryDelay: 200,
});
await mkdir(join(output, 'data'), { recursive: true });
await mkdir(join(output, 'media'), { recursive: true });
await cp(resolve('public/assets/flags'), join(output, 'assets', 'flags'), {
  recursive: true,
});

let copied = 0;
const missing = [];
const picture = (concept) => {
  if (!concept.media) return undefined;
  const web = manifest[concept.media.fileName];
  return web
    ? { path: `media/${web.file}`, width: web.width, height: web.height }
    : undefined;
};
for (const concept of database.concepts) {
  if (!concept.media) continue;
  const web = manifest[concept.media.fileName];
  const file = web
    ? resolve('public/media', web.file)
    : join(database.sourceDirectory, concept.media.fileName);
  if (!existsSync(file)) {
    missing.push(concept.media.fileName);
    continue;
  }
  await cp(file, join(output, 'media', basename(file)));
  copied += 1;
}

// Only the fields the static front end reads, so the payload stays small.
const staticDatabase = {
  version: database.version,
  generatedAt: database.generatedAt,
  sourceDirectory: 'media',
  concepts: database.concepts.map((concept) => ({
    code: concept.code,
    family: concept.family,
    level: concept.level,
    media: picture(concept),
    variants: concept.variants
      .filter((variant) => variant.usable)
      .map((variant) => ({
        id: variant.id,
        code: variant.code,
        route: variant.route,
        sourceLanguage: variant.sourceLanguage,
        targetLanguage: variant.targetLanguage,
        level: variant.level,
        kind: variant.kind,
        prompt: variant.prompt,
        options: variant.options,
        hint: safeHint(variant),
        hintKind: variant.hintKind,
        cloze: variant.cloze,
        answers: variant.answers,
        primaryAnswer: variant.primaryAnswer,
        usable: variant.usable,
      })),
  })),
};

await writeFile(
  join(output, 'data/content-db.json'),
  JSON.stringify(staticDatabase) + '\n',
  'utf8',
);
await writeFile(
  join(output, '.nojekyll'),
  'Static Nebula Tech demo generated by scripts/build-github-pages.mjs.\n',
  'utf8',
);
for (const file of ['index.html', 'styles.css', 'app.js'])
  await cp(join(source, file), join(output, file));

const variants = staticDatabase.concepts.reduce(
  (total, concept) => total + concept.variants.length,
  0,
);
console.log(
  `Static demo written to ${output}: ${staticDatabase.concepts.length} concepts, ${variants} variants, ${copied} pictures.`,
);
if (missing.length)
  console.warn(
    `Missing source pictures (the cards still work without them): ${missing.join(', ')}`,
  );
